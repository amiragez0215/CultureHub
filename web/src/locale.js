export function errorMessage(code, status) {
  return (
    errors[code] ||
    {
      401: "请先登录后再操作",
      403: "你没有执行此操作的权限",
      404: "未找到对应内容",
      429: "操作过于频繁，请稍后再试",
      503: "服务暂不可用，请稍后重试",
    }[status] ||
    "操作未完成，请检查输入信息或稍后重试"
  );
}
function localize(value, key = "") {
  if (value == null) return "暂无";
  if (typeof value === "boolean") return value ? "是" : "否";
  if (
    ["checkinRate", "checkinProgress"].includes(key) &&
    typeof value === "number"
  )
    return `${(value * 100).toFixed(1)}%`;
  if (Array.isArray(value)) return value.map((item) => localize(item));
  if (typeof value === "object")
    return Object.fromEntries(
      Object.entries(value)
        .filter(
          ([k]) =>
            ![
              "request_id",
              "active_guard",
              "eventVersion",
              "promptVersion",
            ].includes(k),
        )
        .map(([k, v]) => [label(k), localize(v, k)]),
    );
  return typeof value === "string" ? label(value) : value;
}
export function displayResult(value) {
  return JSON.stringify(localize(value), null, 2);
}
export function notificationText(raw) {
  try {
    const event = typeof raw === "string" ? JSON.parse(raw) : raw;
    const data = event.data || {};
    return [
      data.title,
      data.startAt && `活动开始：${data.startAt}`,
      data.confirmDeadline && `确认截止：${data.confirmDeadline}`,
    ]
      .filter(Boolean)
      .join("；");
  } catch {
    return "请前往“我的参与”查看当前资格";
  }
}
