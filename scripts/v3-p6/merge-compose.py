"""Generate the complete Compose file from reviewed incremental overlays (requires PyYAML)."""
from pathlib import Path
import copy,json,sys
sys.path.insert(0,str(Path(__file__).resolve().parents[2]/'.tools/v3-p1/python-deps'))
import yaml
root=Path(__file__).resolve().parents[2]
def merge(left,right,key=''):
 if isinstance(left,dict) and isinstance(right,dict):
  result=copy.deepcopy(left)
  for name,value in right.items():result[name]=merge(result[name],value,name) if name in result else copy.deepcopy(value)
  return result
 if isinstance(left,list) and isinstance(right,list) and key in ('volumes','ports'):
  result=copy.deepcopy(left)
  for value in right:
   if value not in result:result.append(copy.deepcopy(value))
  return result
 return copy.deepcopy(right)
result={}
for phase in range(1,7):
 overlay=yaml.safe_load((root/f'compose.v3-p{phase}.yaml').read_text(encoding='utf8'))
 overlay={key:value for key,value in overlay.items() if not key.startswith('x-')}
 result=merge(result,overlay)
result['name']='culturehub-v3'
for service in result['services'].values():
 for volume in service.get('volumes',[]):
  if isinstance(volume,str) and volume.startswith('./'):assert (root/volume.split(':',1)[0]).exists(),volume
assert result['services']['core']['environment']['SPRING_PROFILES_ACTIVE']=='v3-p5'
assert result['services']['ai']['build']['args']['MODULE']=='culturehub-ai'
for service in ('api','core','ai','knowledge','notification','partner-a','partner-b'):
 assert result['services'][service]['environment']['SPRING_CONFIG_ADDITIONAL_LOCATION'].endswith('/v3/observability.properties')
for partner in ('partner-a','partner-b'):assert not result['services'][partner].get('ports')
assert result['services']['seata']['image']=='apache/seata-server:2.5.0'
assert 'seata-data:/seata-server/sessionStore' in result['services']['seata']['volumes']
assert all(result['services'][name]['environment']['SEATA_SERVER_ADDR']=='seata:8091'
           for name in ('core','partner-a','partner-b'))
assert 'rabbitmq' not in result['services']['core'].get('depends_on',{})
assert all('image' in service or 'build' in service for service in result['services'].values())
(root/'compose.v3.yaml').write_text('# Generated by scripts/v3-p6/merge-compose.py; do not edit independently.\n'+yaml.safe_dump(result,sort_keys=False,allow_unicode=True),encoding='utf8')
print('PASS: full Compose generated; profiles, module images, internal Partner ports and volume paths checked')
